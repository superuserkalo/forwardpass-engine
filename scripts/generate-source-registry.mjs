import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const catalog = JSON.parse(await readFile(new URL('../docs/source-catalog.json', import.meta.url), 'utf8'));
const routes = new Map();
for (const source of catalog.sources) {
  for (const page of source.pages) {
    const url = page.fetchUrl || page.url;
    const parsed = new URL(url);
    if (parsed.protocol !== 'https:') throw new Error(`Non-HTTPS catalog route: ${url}`);
    parsed.hash = '';
    const key = parsed.href;
    if (routes.has(key)) { routes.get(key).catalogUrls.push(page.url); continue; }
    const restricted = ['reddit.com', 'alphaxiv.org', 'x.com', 'linkedin.com'].includes(source.host);
    const reference = page.format === 'api-docs' || /api2\.openreview\.net\/groups/.test(url);
    const kind = parsed.hostname === 'hacker-news.firebaseio.com' ? 'hn-list' : page.format === 'rss' || page.format === 'atom' ? page.format
      : page.format === 'json' ? 'json-index'
      : page.format === 'markdown' ? 'markdown' : page.format === 'sitemap' ? 'sitemap' : 'html-news';
    routes.set(key, {
      id: `catalog-${createHash('sha256').update(key).digest('hex').slice(0, 16)}`,
      publisher: source.publisher, publisherId: source.publisherId || source.host,
      host: source.host, section: page.label, category: page.role,
      kind, url: key, catalogUrls: [page.url], ...(page.match ? { match: page.match } : {}),
      access: restricted || page.format === 'social' ? 'permission-required' : reference ? 'reference' : 'public',
      accessReason: restricted ? (typeof source.collectionAccess === 'string' ? source.collectionAccess : source.collectionAccess?.reason) || (source.tags || []).join(', ') : reference ? 'API documentation or group metadata, not a publication stream' : undefined,
      // Matches the two-hour collection run; directories and community pages change slowly.
      intervalHours: /directory|projects|community|resources/.test(page.role) ? 24 : 2,
      verification: page.verification,
      notes: page.collectionNotes || '',
    });
  }
}
const output = '// Generated by scripts/generate-source-registry.mjs from docs/source-catalog.json.\n// Keep the audited catalog as the editable source of truth.\nexport const CATALOG_ROUTES = ' + JSON.stringify([...routes.values()], null, 2) + ' as const;\n';
await writeFile(new URL('../src/lib/source-catalog.generated.ts', import.meta.url), output);
console.log(JSON.stringify({ publishers: catalog.sources.length, routes: routes.size }));
