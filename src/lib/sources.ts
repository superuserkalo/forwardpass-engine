export type SourceTier = keyof typeof SOURCES;

export interface SourceBatch {
  tier: SourceTier;
  domains: string[];
}

const MAX_DOMAINS_PER_SEARCH = 20;

const TIER_ORDER: SourceTier[] = ["primary", "discovery", "signals"];

export const TIER_FOCUS: Record<SourceTier, string> = {
  primary:
    "These are official sources: model labs, platforms, repositories, and paper hosts. Prefer concrete releases, changelogs, model cards, and announcements.",
  discovery:
    "These are high-signal engineering blogs, researcher writing, and aggregators such as Hacker News and Reddit. Find technically significant developments that people building AI systems are discussing.",
  signals:
    "These are broad news and social sources. Use them only as leads: extract concrete technical events and ignore funding, drama, and corporate PR.",
};

export function sourceBatches(): SourceBatch[] {
  const batches: SourceBatch[] = [];
  for (const tier of TIER_ORDER) {
    const domains = [...SOURCES[tier]];
    for (let i = 0; i < domains.length; i += MAX_DOMAINS_PER_SEARCH) {
      batches.push({
        tier,
        domains: domains.slice(i, i + MAX_DOMAINS_PER_SEARCH),
      });
    }
  }
  return batches;
}
